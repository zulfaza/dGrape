import DOMPurify from "dompurify"

// No URL-bearing attributes, embedded documents, animation, or active SVG.
// CSS resource requests are denied by the first policy in the document.
export function staticSnapshot(source: string): string {
  const clean = DOMPurify.sanitize(source, {
    ALLOWED_TAGS: [
      "div",
      "span",
      "p",
      "br",
      "hr",
      "h1",
      "h2",
      "h3",
      "h4",
      "h5",
      "h6",
      "table",
      "thead",
      "tbody",
      "tfoot",
      "tr",
      "td",
      "th",
      "caption",
      "colgroup",
      "col",
      "ul",
      "ol",
      "li",
      "dl",
      "dt",
      "dd",
      "strong",
      "em",
      "b",
      "i",
      "small",
      "pre",
      "code",
      "blockquote",
      "style",
      "svg",
      "g",
      "path",
      "rect",
      "circle",
      "ellipse",
      "line",
      "polyline",
      "polygon",
      "text",
      "tspan",
      "title",
      "desc",
    ],
    ALLOWED_ATTR: [
      "class",
      "style",
      "id",
      "colspan",
      "rowspan",
      "scope",
      "width",
      "height",
      "viewBox",
      "d",
      "x",
      "y",
      "x1",
      "x2",
      "y1",
      "y2",
      "cx",
      "cy",
      "r",
      "rx",
      "ry",
      "points",
      "fill",
      "stroke",
      "stroke-width",
      "transform",
      "text-anchor",
      "font-size",
    ],
    ALLOW_DATA_ATTR: false,
    ALLOW_ARIA_ATTR: false,
  })
  return `<!doctype html><html><head><meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'none'; style-src 'unsafe-inline'; img-src 'none'; connect-src 'none'; object-src 'none'; frame-src 'none'; form-action 'none'; base-uri 'none'; font-src 'none'; media-src 'none'"><meta charset="utf-8"></head><body>${clean}</body></html>`
}
